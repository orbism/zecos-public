/**
 * 8x8 pixel sprites, one per standalone app, drawn into the social-share card
 * so a link to any app is visually distinguishable at a glance.
 *
 * Format: eight strings of eight characters, each character indexing PALETTE.
 * `.` is transparent. Kept tiny on purpose - these render around 12px per cell
 * inside a 1200x630 card and need to read as a silhouette, not an illustration.
 */

export const PALETTE: Record<string, string> = {
  '.': 'transparent',
  g: '#e8b53a', // gold - the house colour
  w: '#eeecf3', // near-white
  b: '#6aa9ff', // blue
  n: '#3ddc84', // green
  o: '#ff8a3d', // orange
  p: '#b48cff', // purple
  r: '#c56b3e', // ironwood brown
  c: '#4dd0c1', // teal
  d: '#4a4a5e', // shadow / outline
};

